#!/usr/bin/env python3
"""Generate Quantumult X resources from a public, credential-free domain list."""
import argparse
import ipaddress
import json
from pathlib import Path
import re
from urllib.parse import urlsplit


def scalar(value, label):
    if not isinstance(value, str) or not value or any(c in value for c in '\r\n,'):
        raise ValueError(f'{label}: expected a nonempty single-line value without commas')
    return value


def render(settings, domains):
    repository = settings['repository']
    if not re.fullmatch(r'[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+', repository):
        raise ValueError('repository: expected owner/repository')
    branch = settings['branch']
    if not re.fullmatch(r'[A-Za-z0-9_.-]+', branch):
        raise ValueError('branch: use a simple branch name')
    prefix = settings.get('path_prefix', '').strip('/')
    if prefix and not re.fullmatch(r'[A-Za-z0-9_-]+(?:/[A-Za-z0-9_-]+)*', prefix):
        raise ValueError('path_prefix: invalid directory')
    policy = scalar(settings['policy_name'], 'policy_name')
    if any(c in policy for c in '=[]') or policy.lower() in {'proxy', 'direct', 'reject', '全球加速'}:
        raise ValueError('policy_name: choose a distinct strategy group name')
    regex = scalar(settings['node_filter'], 'node_filter')
    interval = settings['update_interval']
    if type(interval) is not int or interval < 60:
        raise ValueError('update_interval: expected integer seconds >= 60')
    dns = settings['dns']
    if dns['mode'] not in {'split', 'global'}:
        raise ValueError('dns.mode must be split or global')
    doh = scalar(dns['ai_doh'], 'dns.ai_doh')
    parsed = urlsplit(doh)
    if parsed.scheme != 'https' or not parsed.hostname or parsed.username or parsed.password or parsed.query or parsed.fragment:
        raise ValueError('dns.ai_doh: expected a public HTTPS endpoint without credentials, query or fragment')
    if not isinstance(dns['default_servers'], list) or not dns['default_servers']:
        raise ValueError('dns.default_servers: provide at least one DNS IP')
    for server in dns['default_servers']:
        ipaddress.IPv4Address(server)
    if not isinstance(domains, list):
        raise ValueError('ai-domains.json must contain an array')
    enabled = []
    seen = set()
    for item in domains:
        kind, domain = item['type'], item['domain']
        if kind not in {'suffix', 'exact'}:
            raise ValueError('domain type must be suffix or exact')
        if not isinstance(domain, str) or not re.fullmatch(r'(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\.)+[a-z]{2,63}', domain):
            raise ValueError('domain: expected a lowercase hostname without wildcard or URL')
        if type(item.get('enabled', True)) is not bool:
            raise ValueError('domain enabled must be boolean')
        if item.get('enabled', True) and (kind, domain) not in seen:
            enabled.append((kind, domain))
            seen.add((kind, domain))
    if not enabled:
        raise ValueError('enable at least one domain')
    base = f'https://raw.githubusercontent.com/{repository}/{branch}/'
    if prefix:
        base += prefix + '/'
    rule_url = base + 'rules/ai.list'
    rules = ['# Generated from config/ai-domains.json; use force-policy to select an exit.']
    ai_dns = ['# Merge these lines into your existing [dns] section.',
              '# Selects a DNS resolver; does not guarantee proxy transport.']
    for kind, domain in enabled:
        rules.append(f'{"host-suffix" if kind == "suffix" else "host"}, {domain}, proxy')
        patterns = [domain, '*.' + domain] if kind == 'suffix' else [domain]
        ai_dns.extend(f'doh-server = /{pattern}/{doh}' for pattern in patterns)
    dns_lines = ['no-ipv6', 'no-system']
    if dns['mode'] == 'split':
        dns_lines += [f'server = {server}' for server in dns['default_servers']]
        dns_lines += ai_dns[2:]
    else:
        dns_lines.append(f'doh-server = {doh}')
    remote = f'{rule_url}, tag=自用AI, force-policy={policy}, update-interval={interval}, enabled=true'
    policy_line = f'static = {policy}, proxy, server-tag-regex={regex}'
    integration = '\n'.join([
        '# Merge entries into existing sections; this is NOT a complete profile.',
        '# Select a node in this manual group after importing your private subscription.',
        '[policy]', policy_line, '', '[filter_remote]', remote, '',
        '# DNS entries are in snippets/ai-dns.conf; filter subscriptions cannot update DNS.', ''])
    profile = '\n'.join([
        '# Quantumult X minimal profile; generated by scripts/generate.py.',
        '# Import private nodes locally, then select the AI and global exit nodes.',
        '# DNS mode: ' + dns['mode'] + '. DoH encryption does not imply proxy transport.',
        '[general]', 'server_check_url = http://www.gstatic.com/generate_204',
        'fallback_udp_policy = reject', 'udp_drop_list = STUN, QUIC', '',
        '[dns]', *dns_lines, '', '[policy]', policy_line,
        'static = 全球加速, proxy, server-tag-regex=.*', '',
        '[server_remote]', '# Add your PRIVATE node subscription in the app; keep it out of GitHub.', '',
        '[server_local]', '', '[filter_remote]', remote, '',
        '[filter_local]', 'host-suffix, local, direct',
        'ip-cidr, 10.0.0.0/8, direct', 'ip-cidr, 127.0.0.0/8, direct',
        'ip-cidr, 172.16.0.0/12, direct', 'ip-cidr, 192.168.0.0/16, direct',
        'host-suffix, cn, direct', 'geoip, cn, direct', 'final, 全球加速', '',
        '[rewrite_remote]', '', '[rewrite_local]', '', '[task_local]', '', '[mitm]', ''])
    return {'rules/ai.list': '\n'.join(rules) + '\n',
            'snippets/ai-dns.conf': '\n'.join(ai_dns) + '\n',
            'snippets/integration.conf': integration, 'qx.conf': profile}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--root', type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args()
    try:
        settings = json.loads((args.root / 'config/settings.json').read_text())
        domains = json.loads((args.root / 'config/ai-domains.json').read_text())
        files = render(settings, domains)
    except (ValueError, KeyError, TypeError) as error:
        parser.error(str(error))
    for name, content in files.items():
        path = args.root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding='utf-8')
    print(f'Generated {len(files)} public configuration files')


if __name__ == '__main__':
    main()
